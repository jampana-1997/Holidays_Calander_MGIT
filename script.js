// ============================================================  
  
// YEAR BUTTON ACTIVE  
  
// ============================================================  
  
function updateYearButtons() {  
  
const buttons =  
  
    document.querySelectorAll(  
  
        ".year-selector button"  
  
    );  
  
  
  
  
  
buttons.forEach(button => {  
  
  
  
    if (  
  
        Number(button.textContent) === currentYear  
  
    ) {  
  
  
  
        button.classList.add("active");  
  
  
  
    } else {  
  
  
  
        button.classList.remove("active");  
  
  
  
    }  
  
  
  
});  
  
}  
  
// ============================================================  
  
// PREVIOUS MONTH  
  
// ============================================================  
  
function previousMonth() {  
  
currentMonth--;  
  
  
  
  
  
if (currentMonth < 0) {  
  
  
  
    currentMonth = 11;  
  
    currentYear--;  
  
  
  
}  
  
  
  
  
  
if (currentYear < 2026) {  
  
  
  
    currentYear = 2026;  
  
    currentMonth = 0;  
  
  
  
}  
  
  
  
  
  
renderCalendar();  
  
  
  
updateStatistics();  
  
  
  
updateYearButtons();  
  
}  
  
// ============================================================  
  
// NEXT MONTH  
  
// ============================================================  
  
function nextMonth() {  
  
currentMonth++;  
  
  
  
  
  
if (currentMonth > 11) {  
  
  
  
    currentMonth = 0;  
  
    currentYear++;  
  
  
  
}  
  
  
  
  
  
if (currentYear > 2030) {  
  
  
  
    currentYear = 2030;  
  
    currentMonth = 11;  
  
  
  
}  
  
  
  
  
  
renderCalendar();  
  
  
  
updateStatistics();  
  
  
  
updateYearButtons();  
  
}  
  
