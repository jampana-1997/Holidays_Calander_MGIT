// ============================================================
// CURRENT YEAR / MONTH
// ============================================================

let currentYear = 2026;
let currentMonth = 0;


// ============================================================
// MONTH NAMES
// ============================================================

const monthNames = [
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December"
];


// ============================================================
// GET DATE KEY
// ============================================================

function getDateKey(date) {

    const day = String(date.getDate()).padStart(2, "0");

    const month = String(date.getMonth() + 1).padStart(2, "0");

    const year = date.getFullYear();

    return `${day}-${month}-${year}`;
}


// ============================================================
// WEEKLY HOLIDAY
// Sunday + 2nd Saturday + 4th Saturday
// ============================================================

function getWeeklyHolidayName(date) {

    const day = date.getDay();

    const dateNumber = date.getDate();


    // Sunday
    if (day === 0) {
        return "Sunday";
    }


    // Saturday
    if (day === 6) {

        // 2nd Saturday
        if (dateNumber >= 8 && dateNumber <= 14) {
            return "2nd Saturday";
        }

        // 4th Saturday
        if (dateNumber >= 22 && dateNumber <= 28) {
            return "4th Saturday";
        }
    }


    return null;
}


// ============================================================
// GET HOLIDAY NAME
// ============================================================

function getHolidayName(date) {

    const year = date.getFullYear();

    const dateKey = getDateKey(date);

    const yearHolidays = allHolidays[year] || {};


    // Special holiday first
    if (yearHolidays[dateKey]) {
        return yearHolidays[dateKey];
    }


    // Weekly holiday
    return getWeeklyHolidayName(date);
}


// ============================================================
// HOLIDAY TYPE
// ============================================================

function getHolidayType(date) {

    const year = date.getFullYear();

    const dateKey = getDateKey(date);

    const yearHolidays = allHolidays[year] || {};


    if (yearHolidays[dateKey]) {
        return "special";
    }


    if (getWeeklyHolidayName(date)) {
        return "weekly";
    }


    return "working";
}


// ============================================================
// IS HOLIDAY
// ============================================================

function isHoliday(date) {

    return getHolidayName(date) !== null;
}


// ============================================================
// MONTH STATISTICS
// ============================================================

function updateMonthStatistics() {

    const daysInMonth = new Date(
        currentYear,
        currentMonth + 1,
        0
    ).getDate();


    let holidays = 0;

    let workingDays = 0;


    for (let day = 1; day <= daysInMonth; day++) {

        const date = new Date(
            currentYear,
            currentMonth,
            day
        );


        if (isHoliday(date)) {
            holidays++;
        } else {
            workingDays++;
        }
    }


    document.getElementById("monthTotalDays").textContent =
        daysInMonth;

    document.getElementById("monthHolidays").textContent =
        holidays;

    document.getElementById("monthWorkingDays").textContent =
        workingDays;
}


// ============================================================
// RENDER CALENDAR
// ============================================================

function renderCalendar() {

    const calendar = document.getElementById("calendar");


    if (!calendar) {
        console.error("Calendar element not found!");
        return;
    }


    calendar.innerHTML = "";


    // Month title
    document.getElementById("monthYear").textContent =
        `${monthNames[currentMonth]} ${currentYear}`;


    // First day of month
    const firstDay = new Date(
        currentYear,
        currentMonth,
        1
    ).getDay();


    // Number of days
    const daysInMonth = new Date(
        currentYear,
        currentMonth + 1,
        0
    ).getDate();


    // ========================================================
    // EMPTY CELLS
    // ========================================================

    for (let i = 0; i < firstDay; i++) {

        const emptyDay = document.createElement("div");

        emptyDay.className = "day empty-day";

        calendar.appendChild(emptyDay);
    }


    // ========================================================
    // CREATE DAYS
    // ========================================================

    for (let day = 1; day <= daysInMonth; day++) {

        const date = new Date(
            currentYear,
            currentMonth,
            day
        );


        const dayElement = document.createElement("div");

        dayElement.className = "day";


        // ====================================================
        // DAY NUMBER
        // ====================================================

        const numberElement = document.createElement("div");

        numberElement.className = "day-number";

        numberElement.textContent = day;

        dayElement.appendChild(numberElement);


        // ====================================================
        // HOLIDAY
        // ====================================================

        const holidayName = getHolidayName(date);

        const holidayType = getHolidayType(date);


        if (holidayName) {

            if (holidayType === "special") {

                dayElement.classList.add("special-holiday");

            } else {

                dayElement.classList.add("weekly-holiday");
            }


            const holidayElement =
                document.createElement("div");

            holidayElement.className = "holiday-name";

            holidayElement.textContent = holidayName;

            dayElement.appendChild(holidayElement);
        }


        // ====================================================
        // TODAY
        // ====================================================

        const today = new Date();


        if (
            today.getFullYear() === currentYear &&
            today.getMonth() === currentMonth &&
            today.getDate() === day
        ) {

            dayElement.classList.add("today");
        }


        calendar.appendChild(dayElement);
    }


    // Update month statistics
    updateMonthStatistics();
}


// ============================================================
// YEAR STATISTICS
// ============================================================

function getYearStatistics(year) {

    let totalDays = 0;

    let totalHolidays = 0;

    let workingDays = 0;


    const date = new Date(year, 0, 1);

    const endDate = new Date(year + 1, 0, 1);


    while (date < endDate) {

        totalDays++;


        if (isHoliday(date)) {

            totalHolidays++;

        } else {

            workingDays++;
        }


        date.setDate(date.getDate() + 1);
    }


    return {
        totalDays,
        totalHolidays,
        workingDays
    };
}


// ============================================================
// HOLIDAY PROGRESS
// ============================================================

function getHolidayProgress(year) {

    const today = new Date();


    let completed = 0;

    let remaining = 0;


    const date = new Date(year, 0, 1);

    const endDate = new Date(year + 1, 0, 1);


    while (date < endDate) {

        if (isHoliday(date)) {

            if (date < today) {

                completed++;

            } else {

                remaining++;
            }
        }


        date.setDate(date.getDate() + 1);
    }


    return {
        completed,
        remaining
    };
}


// ============================================================
// UPDATE YEAR STATISTICS
// ============================================================

function updateStatistics() {

    const stats =
        getYearStatistics(currentYear);


    const progress =
        getHolidayProgress(currentYear);


    document.getElementById("totalDays").textContent =
        stats.totalDays;


    document.getElementById("totalHolidays").textContent =
        stats.totalHolidays;


    document.getElementById("completedHolidays").textContent =
        progress.completed;


    document.getElementById("remainingHolidays").textContent =
        progress.remaining;


    document.getElementById("workingDays").textContent =
        stats.workingDays;
}


// ============================================================
// CHANGE YEAR
// ============================================================

function changeYear(year) {

    currentYear = Number(year);

    currentMonth = 0;


    renderCalendar();

    updateStatistics();

    updateYearButtons();
}


// ============================================================
// ACTIVE YEAR BUTTON
// ============================================================

function updateYearButtons() {

    const buttons =
        document.querySelectorAll(
            ".year-selector button"
        );


    buttons.forEach(button => {

        const buttonYear =
            Number(button.textContent.trim());


        if (buttonYear === currentYear) {

            button.classList.add("active");

        } else {

            button.classList.remove("active");
        }
    });
}


// ============================================================
// PREVIOUS MONTH
// ============================================================

function previousMonth() {

    currentMonth--;


    if (currentMonth < 0) {

        currentMonth = 11;

        currentYear--;
    }


    if (currentYear < 2026) {

        currentYear = 2026;

        currentMonth = 0;
    }


    renderCalendar();

    updateStatistics();

    updateYearButtons();
}


// ============================================================
// NEXT MONTH
// ============================================================

function nextMonth() {

    currentMonth++;


    if (currentMonth > 11) {

        currentMonth = 0;

        currentYear++;
    }


    if (currentYear > 2030) {

        currentYear = 2030;

        currentMonth = 11;
    }


    renderCalendar();

    updateStatistics();

    updateYearButtons();
}


